using AwesomeAssertions;

namespace Humans.Analyzers.Tests;

public class HumanNameRenderingAnalyzerTests
{
    private const string Stubs = """
        namespace Humans.Users.Contracts
        {
            public sealed record UserInfo(string BurnerName);
        }

        namespace Razor
        {
            public abstract class Page
            {
                public void Write(object? value) { }
                public void WriteAttributeValue(string prefix, int prefixOffset, object? value, int valueOffset, int valueLength, bool isLiteral) { }
            }
        }
        """;

    private static Task<System.Collections.Immutable.ImmutableArray<Microsoft.CodeAnalysis.Diagnostic>> RunAsync(string source) =>
        AnalyzerTestHarness.RunAsync(new HumanNameRenderingAnalyzer(), "Humans.Finance", source);

    private static bool IsHum0041(Microsoft.CodeAnalysis.Diagnostic d) =>
        string.Equals(d.Id, HumanNameRenderingAnalyzer.DiagnosticId, StringComparison.Ordinal);

    [HumansFact]
    public async Task Fires_on_a_view_writing_BurnerName_but_not_on_sorting_by_it()
    {
        var source = "// <auto-generated/>\n" + Stubs + """

            namespace AspNetCoreGeneratedDocument
            {
                using System.Collections.Generic;
                using System.Linq;
                using Humans.Users.Contracts;

                public sealed class Views_Finance_Index : Razor.Page
                {
                    public void Render(UserInfo? info, List<UserInfo> people)
                    {
            #line 10 "/src/Sections/Humans.Finance/Views/Finance/Index.cshtml"
                        Write(info?.BurnerName ?? "—");
                        WriteAttributeValue("", 0, $"by {info!.BurnerName}", 0, 0, false);
                        _ = people.OrderBy(p => p.BurnerName).ToList();
            #line default
                    }

                    public void ComponentInternals(UserInfo info)
                    {
                        Write(info.BurnerName);
                    }
                }
            }
            """;

        var diagnostics = (await RunAsync(source)).Where(IsHum0041).ToList();

        diagnostics.Should().HaveCount(2);
        diagnostics.Should().OnlyContain(d => d.Location.GetMappedLineSpan().Path.EndsWith("Index.cshtml", StringComparison.Ordinal));
    }
}

using AwesomeAssertions;
using Microsoft.CodeAnalysis;

namespace Humans.Analyzers.Tests;

public class PartialTypeAcrossFilesAnalyzerTests
{
    private const string GrandfatheredStub = """
        namespace Humans.Base.Attributes
        {
            [System.AttributeUsage(System.AttributeTargets.Class, AllowMultiple = true)]
            public sealed class GrandfatheredAttribute : System.Attribute
            {
                public GrandfatheredAttribute(string ruleId, string justification, string since, string issueRef) { }
            }
        }
        """;

    private static Task<System.Collections.Immutable.ImmutableArray<Diagnostic>> RunAsync(
        string source, params (string Path, string Text)[] extra) =>
        AnalyzerTestHarness.RunAsync(
            new PartialTypeAcrossFilesAnalyzer(), "Humans.Sample", source, sourcePath: "Service.cs", extraSources: extra);

    private static IEnumerable<Diagnostic> Hum0046(IEnumerable<Diagnostic> diagnostics) =>
        diagnostics.Where(d => string.Equals(d.Id, PartialTypeAcrossFilesAnalyzer.DiagnosticId, StringComparison.Ordinal));

    [HumansFact]
    public async Task PartialAcrossTwoFiles_Error()
    {
        var diagnostics = await RunAsync(
            "namespace S; internal sealed partial class Service { public void A() { } }",
            ("Service.More.cs", "namespace S; internal sealed partial class Service { public void B() { } }"));

        var hit = Hum0046(diagnostics).Should().ContainSingle().Subject;
        hit.Severity.Should().Be(DiagnosticSeverity.Error);
        hit.Location.SourceTree!.FilePath.Should().Be("Service.More.cs");
    }

    [HumansFact]
    public async Task PartialInterfaceAcrossFiles_Error()
    {
        var diagnostics = await RunAsync(
            "namespace S; internal partial interface IRepo { void A(); }",
            ("IRepo.More.cs", "namespace S; internal partial interface IRepo { void B(); }"));

        Hum0046(diagnostics).Should().ContainSingle();
    }

    [HumansFact]
    public async Task PartialTwiceInOneFile_NoDiagnostic()
    {
        var diagnostics = await RunAsync(
            "namespace S; internal partial class Service { } internal partial class Service { }");

        Hum0046(diagnostics).Should().BeEmpty();
    }

    [HumansFact]
    public async Task OtherHalfGenerated_NoDiagnostic()
    {
        var diagnostics = await RunAsync(
            "namespace S; internal partial class Migration1 { }",
            ("Migration1.Designer.cs", "namespace S; internal partial class Migration1 { }"),
            ("Gen/Service.g.cs", "namespace S; internal partial class Migration1 { }"),
            ("Other.cs", "// <auto-generated/>\nnamespace S; internal partial class Migration1 { }"));

        Hum0046(diagnostics).Should().BeEmpty();
    }

    [HumansFact]
    public async Task Grandfathered_Warning()
    {
        var diagnostics = await RunAsync(
            GrandfatheredStub + """

            namespace S
            {
                [Humans.Base.Attributes.Grandfathered("HUM0046", "split pending", "2026-11-27", "x#1")]
                internal sealed partial class Service { }
            }
            """,
            ("Service.More.cs", "namespace S { internal sealed partial class Service { } }"));

        Hum0046(diagnostics).Should().ContainSingle().Which.Severity.Should().Be(DiagnosticSeverity.Warning);
    }
}

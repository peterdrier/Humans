// Look-and-feel capture harness: visits every route of the Humans web app on QA and records
// screenshots + layout metrics per page (desktop, and mobile for non-admin-shell pages).
// Usage: LOOK_AUDIT_LOGIN_URL=... node capture.mjs [--run <id>] [--only <substr>] [--limit N] [--routes <file>]
import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { PNG } from 'pngjs';

// ESM import ignores NODE_PATH, which is how the globally installed playwright resolves here.
const { chromium } = createRequire(import.meta.url)('playwright');
const axeSource = fs.readFileSync(createRequire(import.meta.url).resolve('axe-core/axe.min.js'), 'utf8');

// Backstop for GETs that look like they have side effects or aren't pages (template and action name).
const SKIP_RE = /logout|signout|delete|remove|export|download|sync|approve|reject|confirm|unsubscribe|impersonat|exit|backfill|run|trigger|send|resend|reset|seed|toggle|accept|decline|cancel|claim|join|leave|peek|csv|xlsx|picture|barcode|externallogincallback|magiclinkconfirm|\.(csv|json)$/i;
const MAX_PARAM_PASSES = 3;
const CONCURRENCY = 3;

const here = path.dirname(fileURLToPath(import.meta.url));
const args = Object.fromEntries(process.argv.slice(2).reduce((a, v, i, all) => (v.startsWith('--') ? [...a, [v.slice(2), all[i + 1] && !all[i + 1].startsWith('--') ? all[i + 1] : true]] : a), []));
const BASE = (process.env.LOOK_AUDIT_BASE_URL || 'https://humans.n.burn.camp').replace(/\/$/, '');
const LOGIN_URL = process.env.LOOK_AUDIT_LOGIN_URL;
if (!LOGIN_URL) { console.error('LOOK_AUDIT_LOGIN_URL is not set'); process.exit(1); }
const redact = s => String(s).split(LOGIN_URL).join('[login-url]');

const runId = args.run && args.run !== true ? args.run : new Date().toISOString().replace(/\.\d+Z$/, '').replace(/[-:]/g, '').replace('T', '-');
const outDir = path.join(here, 'out', runId);
const shotDir = path.join(outDir, 'shots');
fs.mkdirSync(shotDir, { recursive: true });
const pagesFile = path.join(outDir, 'pages.json');
const harvestFile = path.join(outDir, 'harvest.json');

const routesFile = args.routes && args.routes !== true ? args.routes : path.join(here, 'out', 'routes.json');
const allRoutes = JSON.parse(fs.readFileSync(routesFile, 'utf8')).routes;

const slug = s => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 50) || 'root';
const routes = allRoutes.map((r, i) => ({ ...r, id: `${String(i).padStart(3, '0')}-${slug(r.template)}` }));

const rows = new Map(fs.existsSync(pagesFile) ? JSON.parse(fs.readFileSync(pagesFile, 'utf8')).map(r => [r.id, r]) : []);
const harvested = new Set(fs.existsSync(harvestFile) ? JSON.parse(fs.readFileSync(harvestFile, 'utf8')) : []);
const save = () => {
  fs.writeFileSync(pagesFile + '.tmp', JSON.stringify([...rows.values()].sort((a, b) => a.id.localeCompare(b.id)), null, 1));
  fs.renameSync(pagesFile + '.tmp', pagesFile);
  fs.writeFileSync(harvestFile, JSON.stringify([...harvested].sort()));
};
const isDone = id => rows.has(id) && rows.get(id).status !== 'no-sample';

// "/Teams/{slug}" -> regex; constraints ({id:guid}) are ignored, optional params match an absent segment.
function templateRegex(t) {
  const src = t.split('/').filter(Boolean).map(seg => {
    const m = seg.match(/^\{\*?(\w+)(?::[^}?]*)?(\??)\}$/);
    if (m) return m[2] ? '(?:/[^/]+)?' : '/[^/]+';
    return '/' + seg.replace(/[.*+?^${}()|[\]\\]/g, '\\$&').replace(/\\\{[^}]*\\\}|\{[^}]*\}/g, '[^/]+');
  }).join('');
  return new RegExp(`^${src || '/'}/?$`, 'i');
}
const literalWeight = t => t.replace(/\{[^}]*\}/g, '').length;

// Only routes reviewed as side-effect free are visited (route-review.json, regenerated by reading each
// GET action whenever routes change). A new or changed route stays unvisited until reviewed: an admin
// crawl must never record audit entries, peeks or writes. SKIP_RE is a second net, not the gate.
const review = JSON.parse(fs.readFileSync(path.join(here, 'route-review.json'), 'utf8')).routes;
const skipReason = r => {
  if (/^\/dev(\/|$)/i.test(r.template)) return 'dev path';
  const rv = review[r.template];
  if (!rv) return 'not reviewed for side effects';
  if (!rv.safe) return `side effect: ${rv.reason}`;
  const m = r.template.match(SKIP_RE) || (r.action || '').match(SKIP_RE);
  return m ? `side-effect pattern "${m[0]}"` : null;
};

// ---------- in-page metrics ----------
function collectMetrics({ mobile }) {
  const vw = innerWidth, vh = innerHeight;
  const vis = el => el.checkVisibility({ checkOpacity: true, checkVisibilityCSS: true });
  const rectOf = el => el.getBoundingClientRect();
  const words = { above: 0, total: 0 };
  const fontSizes = new Set(), textColors = new Set();
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  for (let n; (n = walker.nextNode());) {
    const el = n.parentElement;
    const t = n.nodeValue.trim();
    if (!t || !el || /^(SCRIPT|STYLE|NOSCRIPT|TEMPLATE)$/.test(el.tagName) || !vis(el)) continue;
    const r = rectOf(el);
    if (r.width === 0 || r.height === 0 || r.bottom <= 0 || r.right <= 0) continue;
    const w = t.split(/\s+/).length;
    words.total += w;
    if (r.top < vh) words.above += w;
    const cs = getComputedStyle(el);
    fontSizes.add(cs.fontSize); textColors.add(cs.color);
  }
  const visible = sel => [...document.querySelectorAll(sel)].filter(el => {
    if (!vis(el)) return false;
    const r = rectOf(el);
    return r.width > 1 || r.height > 1;
  });
  const interactiveSel = 'a, button, input:not([type=hidden]), select, textarea';
  const interactive = visible(interactiveSel);
  const actions = visible('button, input[type=submit], a.btn').filter(el => { const r = rectOf(el); return r.top < vh && r.bottom > 0; });

  const tables = visible('table');
  const colsOf = t => Math.max(0, ...[...t.rows].map(tr => [...tr.cells].reduce((s, c) => s + (c.colSpan || 1), 0)));
  const sharedTables = tables.filter(t => t.closest('.table-component')).length;

  // Clipped by a scroll/hidden ancestor = not page overflow.
  const clipped = el => { for (let p = el.parentElement; p && p !== document.documentElement; p = p.parentElement) { if (getComputedStyle(p).overflowX !== 'visible') return true; } return false; };
  let overflowCount = 0;
  for (const el of document.body.querySelectorAll('*')) {
    const r = rectOf(el);
    if (r.right > vw + 1 && r.width > 0 && vis(el) && !clipped(el)) overflowCount++;
  }

  let wrappedCells = 0;
  for (const c of visible('td, th')) {
    if (!c.textContent.trim()) continue;
    const cs = getComputedStyle(c);
    const lh = parseFloat(cs.lineHeight) || parseFloat(cs.fontSize) * 1.2;
    const range = document.createRange(); range.selectNodeContents(c);
    if (range.getBoundingClientRect().height > 2.5 * lh) wrappedCells++;
  }

  // page-header tag helper emits <h1 class="mb-0"> inside a div.mb-4 band; any other h1 is hand-rolled.
  const h1s = visible('h1');
  const sharedHeaders = h1s.filter(h => h.classList.contains('mb-0') && h.closest('div.mb-4')).length;

  const m = {
    screens: +(document.documentElement.scrollHeight / vh).toFixed(1),
    wordsAboveFold: words.above, wordsTotal: words.total,
    interactive: interactive.length, actionsAboveFold: actions.length,
    tables: tables.length, maxTableCols: Math.max(0, ...tables.map(colsOf)),
    fontSizes: [...fontSizes], textColors: [...textColors],
    hOverflow: document.documentElement.scrollWidth > document.documentElement.clientWidth, overflowCount,
    wrappedCells,
    shared: {
      tablesShared: sharedTables, tablesOther: tables.length - sharedTables,
      headersShared: sharedHeaders, headersOther: h1s.length - sharedHeaders,
      badges: visible('.badge').length, // status-badge has no unique markup, so badges stay out of the ratio
    },
    bg: getComputedStyle(document.body).backgroundColor,
    htmlBg: getComputedStyle(document.documentElement).backgroundColor,
  };
  const denom = m.shared.tablesShared + m.shared.tablesOther + m.shared.headersShared + m.shared.headersOther;
  m.shared.sharedRatio = denom ? +((m.shared.tablesShared + m.shared.headersShared) / denom).toFixed(2) : null;
  if (mobile) m.smallTapTargets = interactive.filter(el => { const r = rectOf(el); return r.width < 44 || r.height < 44; }).length;
  return m;
}

function inkDensity(buf, bgCss, htmlBgCss) {
  const parse = c => { const m = c.match(/[\d.]+/g)?.map(Number) || []; return m.length >= 3 ? { r: m[0], g: m[1], b: m[2], a: m[3] ?? 1 } : null; };
  let bg = parse(bgCss);
  if (!bg || bg.a === 0) bg = parse(htmlBgCss);
  if (!bg || bg.a === 0) bg = { r: 255, g: 255, b: 255, a: 1 };
  const mix = v => v * bg.a + 255 * (1 - bg.a);
  const [br, bgG, bb] = [mix(bg.r), mix(bg.g), mix(bg.b)];
  const { data, width, height } = PNG.sync.read(buf);
  let ink = 0;
  for (let i = 0; i < data.length; i += 4) {
    if (Math.max(Math.abs(data[i] - br), Math.abs(data[i + 1] - bgG), Math.abs(data[i + 2] - bb)) > 16) ink++;
  }
  return +(ink / (width * height)).toFixed(3);
}

// ---------- per-page capture ----------
async function dismissCookies(page, state) {
  if (state.done) return;
  const btn = page.locator('#cookieConsent').getByRole('button', { name: 'Accept' });
  if (await btn.isVisible().catch(() => false)) {
    await btn.click({ timeout: 3000 }).catch(() => {});
    state.done = true;
    await page.waitForTimeout(300);
  }
}

async function capture(ctxInfo, url, id, tag) {
  const { ctx, mobile, cookies } = ctxInfo;
  const page = await ctx.newPage();
  page.setDefaultTimeout(30000);
  const consoleErrors = [], failed = [];
  page.on('console', m => { if (m.type() === 'error') consoleErrors.push(redact(m.text()).slice(0, 200)); });
  page.on('pageerror', e => consoleErrors.push(redact(e.message).slice(0, 200)));
  page.on('requestfailed', r => { const e = r.failure()?.errorText || ''; if (!/ERR_ABORTED/.test(e)) failed.push(`${e} ${r.method()} ${redact(r.url()).slice(0, 150)}`); });
  page.on('response', r => { if (r.status() >= 400 && !(r.request().isNavigationRequest() && r.frame() === page.mainFrame())) failed.push(`${r.status()} ${r.request().method()} ${redact(r.url()).slice(0, 150)}`); });
  const out = { final: null, httpStatus: null, contentType: null, status: 'ok', links: [] };
  try {
    let resp;
    try { resp = await page.goto(BASE + url, { waitUntil: 'load' }); }
    catch (e) {
      if (/Download is starting/.test(e.message)) { out.status = 'non-html'; return out; }
      throw e;
    }
    out.final = page.url().replace(BASE, '');
    out.httpStatus = resp.status();
    out.contentType = (resp.headers()['content-type'] || '').split(';')[0];
    if (/\/Account\/(AccessDenied|Login)|\/Identity\/Account\/(AccessDenied|Login)/i.test(out.final) || [401, 403].includes(out.httpStatus)) { out.status = 'denied'; return out; }
    if (out.httpStatus >= 400) { out.status = 'error'; return out; }
    if (!/html/i.test(out.contentType)) { out.status = 'non-html'; return out; }
    // A redirect lands on another route's page, which is scored under that route; scoring it twice skews section medians.
    if (out.final.split('?')[0].replace(/\/$/, '').toLowerCase() !== url.split('?')[0].replace(/\/$/, '').toLowerCase()) { out.status = 'redirect'; return out; }
    // Partial-view endpoints (popups, cards loaded into another page) have no stylesheet of their own.
    if (await page.evaluate(() => document.styleSheets.length === 0)) { out.status = 'fragment'; return out; }
    out.networkIdle = await page.waitForLoadState('networkidle', { timeout: 30000 }).then(() => true, () => false);
    await dismissCookies(page, cookies);

    out.links = await page.evaluate(() => [...document.querySelectorAll('a[href]')].map(a => { try { const u = new URL(a.href); return u.origin === location.origin ? u.pathname : null; } catch { return null; } }).filter(Boolean));
    out.adminLayout = await page.evaluate(() => document.body.classList.contains('admin-shell'));

    const fold = await page.screenshot({ animations: 'disabled' });
    fs.writeFileSync(path.join(shotDir, `${id}-${tag}-fold.png`), fold);
    const metrics = await page.evaluate(collectMetrics, { mobile });
    metrics.inkDensity = inkDensity(fold, metrics.bg, metrics.htmlBg);
    delete metrics.bg; delete metrics.htmlBg;
    const consoleCount = consoleErrors.length, failedCount = failed.length;
    if (!mobile) {
      // Evaluate rather than addScriptTag: the site CSP blocks injected inline scripts. axe's own fetches
      // also trip connect-src, so stop recording page noise before it runs.
      await page.evaluate(axeSource);
      const res = await page.evaluate(() => axe.run(document, { resultTypes: ['violations'] }));
      metrics.axe = { critical: 0, serious: 0, moderate: 0, minor: 0, nodes: 0, rules: res.violations.map(v => v.id) };
      for (const v of res.violations) { metrics.axe[v.impact] = (metrics.axe[v.impact] || 0) + 1; metrics.axe.nodes += v.nodes.length; }
    }
    consoleErrors.length = consoleCount; failed.length = failedCount;
    await page.screenshot({ fullPage: true, animations: 'disabled', path: path.join(shotDir, `${id}-${tag}.png`) });
    metrics.shot = `shots/${id}-${tag}.png`; metrics.fold = `shots/${id}-${tag}-fold.png`;
    metrics.consoleErrors = { count: consoleErrors.length, first: consoleErrors.slice(0, 3) };
    metrics.failedRequests = { count: failed.length, first: failed.slice(0, 3) };
    out.metrics = metrics;
    return out;
  } finally {
    await page.close().catch(() => {});
  }
}

async function visit(desktop, mobile, route, url) {
  const row = { id: route.id, section: route.section, template: route.template, controller: route.controller, action: route.action, anonymous: route.anonymous, sampledUrl: url, capturedAt: new Date().toISOString() };
  try {
    const d = await capture(desktop, url, route.id, 'desktop');
    Object.assign(row, { status: d.status, finalUrl: d.final, httpStatus: d.httpStatus, contentType: d.contentType, adminLayout: d.adminLayout ?? null, networkIdle: d.networkIdle ?? null, desktop: d.metrics ?? null, mobile: null });
    if (d.status === 'ok') {
      for (const l of d.links) harvested.add(l);
      if (!d.adminLayout) row.mobile = (await capture(mobile, url, route.id, 'mobile')).metrics ?? null;
    }
  } catch (e) {
    Object.assign(row, { status: 'error', error: redact(e.message).split('\n')[0].slice(0, 300), desktop: null, mobile: null });
  }
  rows.set(route.id, row);
  save();
  console.log(`${row.status.padEnd(8)} ${row.id}  ${url}${row.adminLayout ? '  [admin]' : ''}`);
}

async function pool(items, fn) {
  const queue = [...items];
  await Promise.all(Array.from({ length: CONCURRENCY }, async () => { for (let it; (it = queue.shift());) await fn(it); }));
}

// ---------- main ----------
let todo = routes.filter(r => !args.only || r.template.toLowerCase().includes(String(args.only).toLowerCase()));
if (args.limit) todo = todo.slice(0, +args.limit);

for (const r of todo) {
  const reason = skipReason(r);
  if (reason && !isDone(r.id)) rows.set(r.id, { id: r.id, section: r.section, template: r.template, controller: r.controller, action: r.action, status: 'skipped', reason });
}

const browser = await chromium.launch();
const mkCtx = async (mobile, storageState) => ({
  mobile,
  cookies: { done: false },
  ctx: await browser.newContext(mobile
    ? { viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 1, storageState }
    : { viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1, storageState }),
});

let desktop;
try {
  desktop = await mkCtx(false);
  const p = await desktop.ctx.newPage();
  const resp = await p.goto(LOGIN_URL, { waitUntil: 'load' }).catch(e => { throw new Error(redact(e.message).split('\n')[0]); });
  const landed = new URL(p.url());
  if (!resp.ok() || /login|denied/i.test(landed.pathname)) throw new Error(`sign-in failed (status ${resp.status()}, landed on ${landed.pathname})`);
  await p.close();
} catch (e) { console.error('Sign-in failed:', redact(e.message)); await browser.close(); process.exit(1); }
const mobileCtx = await mkCtx(true, await desktop.ctx.storageState());

const pending = todo.filter(r => !isDone(r.id));
const plain = pending.filter(r => !r.hasParams);
const parametric = pending.filter(r => r.hasParams);
console.log(`run ${runId}: ${plain.length} plain, ${parametric.length} parametric, ${todo.length - pending.length} done/skipped`);

await pool(plain, r => visit(desktop, mobileCtx, r, '/' + r.template.split('/').filter(Boolean).join('/')));

// Fill params from harvested links; a link may only fill the template it matches best (most literal text),
// and never one that is itself a concrete route (e.g. /Teams/Create is not a {slug}).
const literalRoutes = routes.filter(r => !r.hasParams).map(r => templateRegex(r.template));
const paramRoutes = routes.filter(r => r.hasParams).map(r => ({ r, re: templateRegex(r.template), w: literalWeight(r.template) }));
let left = parametric;
for (let pass = 1; pass <= MAX_PARAM_PASSES && left.length; pass++) {
  const matches = [];
  for (const r of left) {
    const re = templateRegex(r.template);
    const href = [...harvested].find(h => {
      if (h === '/' || SKIP_RE.test(h) || /^\/dev(\/|$)/i.test(h) || literalRoutes.some(l => l.test(h)) || !re.test(h)) return false;
      const best = paramRoutes.filter(p => p.re.test(h)).sort((a, b) => b.w - a.w)[0];
      return best?.r.template === r.template;
    });
    if (href) matches.push([r, href]);
  }
  if (!matches.length) break;
  console.log(`param pass ${pass}: ${matches.length} filled`);
  await pool(matches, ([r, href]) => visit(desktop, mobileCtx, r, href));
  left = left.filter(r => !matches.some(([m]) => m === r));
}
for (const r of left) {
  rows.set(r.id, { id: r.id, section: r.section, template: r.template, controller: r.controller, action: r.action, status: 'no-sample' });
  console.log(`no-sample ${r.id}  ${r.template}`);
}
save();
await browser.close();
const counts = {};
for (const r of rows.values()) counts[r.status] = (counts[r.status] || 0) + 1;
console.log('done', runId, JSON.stringify(counts));

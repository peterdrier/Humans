using System;
using System.Collections.Immutable;
using System.Linq;
using Humans.Analyzers.Internal;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Diagnostics;

namespace Humans.Analyzers;

/// <summary>
/// HUM0046: a hand-written type lives in one file. <c>partial</c> exists for generated code
/// (<c>[GeneratedRegex]</c>, <c>[LoggerMessage]</c>, EF designers, Razor); slicing a hand-written
/// class across files hides a god class instead of splitting it
/// (memory/architecture/one-service-class-no-helpers.md).
/// </summary>
[DiagnosticAnalyzer(LanguageNames.CSharp)]
public sealed class PartialTypeAcrossFilesAnalyzer : DiagnosticAnalyzer
{
    public const string DiagnosticId = "HUM0046";

    public static readonly DiagnosticDescriptor Rule = new(
        id: DiagnosticId,
        title: "Hand-written type declared across several files",
        messageFormat: "'{0}' is declared in {1} hand-written files; a type lives in one file — fold it back, or split " +
                       "a real job out into its own service (memory/architecture/one-service-class-no-helpers.md)",
        category: AnalyzerCategories.Structure,
        defaultSeverity: DiagnosticSeverity.Error,
        isEnabledByDefault: true,
        description: "partial is for generated code only. Splitting a hand-written type across files hides its size.");

    public override ImmutableArray<DiagnosticDescriptor> SupportedDiagnostics => [Rule];

    public override void Initialize(AnalysisContext context)
    {
        context.ConfigureGeneratedCodeAnalysis(GeneratedCodeAnalysisFlags.None);
        context.EnableConcurrentExecution();
        context.RegisterCompilationStartAction(start =>
        {
            var grandfathered = GrandfatheredCheck.Resolve(start.Compilation);
            start.RegisterSymbolAction(c => Analyze(c, grandfathered), SymbolKind.NamedType);
        });
    }

    private static void Analyze(SymbolAnalysisContext context, INamedTypeSymbol? grandfathered)
    {
        var type = (INamedTypeSymbol)context.Symbol;
        if (type.DeclaringSyntaxReferences.Length < 2)
            return;

        var trees = type.DeclaringSyntaxReferences
            .Select(r => r.SyntaxTree)
            .Where(t => !IsGenerated(t, context.CancellationToken))
            .Distinct()
            // The home file (named for the type, else the longest) stays quiet; every other file is flagged.
            .OrderBy(t => string.Equals(System.IO.Path.GetFileName(t.FilePath), type.Name + ".cs", StringComparison.OrdinalIgnoreCase) ? 0 : 1)
            .ThenByDescending(t => t.Length)
            .ToList();
        if (trees.Count < 2)
            return;

        var severity = GrandfatheredCheck.HasGrandfatherFor(type, grandfathered, DiagnosticId)
            ? DiagnosticSeverity.Warning
            : DiagnosticSeverity.Error;

        foreach (var reference in type.DeclaringSyntaxReferences.Where(r => trees.Skip(1).Contains(r.SyntaxTree)))
        {
            context.ReportDiagnostic(Diagnostic.Create(
                Rule,
                reference.GetSyntax(context.CancellationToken).GetLocation(),
                severity,
                additionalLocations: null,
                properties: null,
                type.Name,
                trees.Count));
        }
    }

    private static bool IsGenerated(SyntaxTree tree, System.Threading.CancellationToken ct)
    {
        var path = tree.FilePath;
        if (path.EndsWith(".g.cs", StringComparison.OrdinalIgnoreCase)
            || path.EndsWith(".g.i.cs", StringComparison.OrdinalIgnoreCase)
            || path.EndsWith(".designer.cs", StringComparison.OrdinalIgnoreCase)
            || path.EndsWith(".generated.cs", StringComparison.OrdinalIgnoreCase))
            return true;

        return tree.GetRoot(ct).GetLeadingTrivia()
            .Any(t => t.ToString().IndexOf("<auto-generated", StringComparison.OrdinalIgnoreCase) >= 0);
    }
}

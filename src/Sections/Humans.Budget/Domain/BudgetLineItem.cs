using NodaTime;

namespace Humans.Budget.Domain;

internal sealed class BudgetLineItem
{
    public Guid Id { get; init; }
    public Guid BudgetCategoryId { get; init; }
    public BudgetCategory? BudgetCategory { get; set; }
    public string Description { get; set; } = string.Empty;
    public decimal Amount { get; set; }
    public Guid? ResponsibleTeamId { get; set; }
    public string? Notes { get; set; }

    /// <summary>Used for cashflow projections.</summary>
    public LocalDate? ExpectedDate { get; set; }

    /// <summary>Percent, 0–21.</summary>
    public int VatRate { get; set; }

    /// <summary>Written by the ticketing sync, not by hand.</summary>
    public bool IsAutoGenerated { get; set; }

    /// <summary>Affects cashflow only (e.g. donations): excluded from income, expense and profit.</summary>
    public bool IsCashflowOnly { get; set; }

    public int SortOrder { get; set; }
    public Instant CreatedAt { get; init; }
    public Instant UpdatedAt { get; set; }
}

using Humans.Base.Interfaces;
using NodaTime;

namespace Humans.Budget.Contracts;

/// <summary>Cross-section budget reads. DTOs only.</summary>
public interface IBudgetService : IApplicationService
{
    /// <summary>The full group, category and line-item projection; null when no year is active.</summary>
    Task<BudgetYearDetail?> GetActiveYearAsync(CancellationToken ct = default);

    /// <summary>
    /// Same projection as <see cref="GetActiveYearAsync"/>, for any year: a pending expense report may be booked to a
    /// year that is no longer active.
    /// </summary>
    Task<BudgetYearDetail?> GetYearByIdAsync(Guid id, CancellationToken ct = default);

    /// <summary>With its group, year and line items.</summary>
    Task<BudgetCategorySnapshot?> GetCategoryByIdAsync(Guid id, CancellationToken ct = default);

    /// <summary>Pure computation over <paramref name="groups"/>; no I/O.</summary>
    BudgetSummaryResult ComputeBudgetSummary(IReadOnlyList<BudgetGroupDetail> groups);
}

public sealed record BudgetYearDetail(
    Guid Id,
    string Year,
    string Name,
    BudgetYearStatus Status,
    bool IsArchived,
    IReadOnlyList<BudgetGroupDetail> Groups,
    string? PlatformEventId = null);

public sealed record BudgetGroupDetail(
    Guid Id,
    Guid BudgetYearId,
    string Name,
    int SortOrder,
    bool IsRestricted,
    bool IsDepartmentGroup,
    bool IsTicketingGroup,
    TicketingProjectionSnapshot? TicketingProjection,
    IReadOnlyList<BudgetCategoryDetail> Categories)
{
    internal decimal AllocatedAmount => Categories.Sum(category => category.AllocatedAmount);
    internal decimal LineItemTotal => Categories.Sum(category => category.LineItemTotal);
    internal decimal AvailableAmount => AllocatedAmount - LineItemTotal;
}

public sealed record BudgetCategoryDetail(
    Guid Id,
    string Name,
    decimal AllocatedAmount,
    ExpenditureType ExpenditureType,
    Guid? TeamId,
    int SortOrder,
    IReadOnlyList<BudgetLineItemDetail> LineItems)
{
    internal decimal LineItemTotal => LineItems.Where(item => !item.IsCashflowOnly).Sum(item => item.Amount);
    internal decimal AvailableAmount => AllocatedAmount - LineItemTotal;
}

public sealed record BudgetLineItemDetail(
    Guid Id,
    string Description,
    decimal Amount,
    Guid? ResponsibleTeamId,
    string? Notes,
    LocalDate? ExpectedDate,
    int VatRate,
    bool IsAutoGenerated,
    bool IsCashflowOnly,
    int SortOrder);

public sealed record TicketingProjectionSnapshot(
    LocalDate? StartDate,
    LocalDate? EventDate,
    int InitialSalesCount,
    decimal DailySalesRate,
    decimal AverageTicketPrice,
    int VatRate,
    decimal StripeFeePercent,
    decimal StripeFeeFixed,
    decimal PlatformFeePercent);

public sealed record BudgetCategorySnapshot(
    Guid Id,
    Guid BudgetGroupId,
    string Name,
    decimal AllocatedAmount,
    ExpenditureType ExpenditureType,
    Guid? TeamId,
    int SortOrder,
    BudgetCategoryGroupSnapshot? BudgetGroup,
    IReadOnlyList<BudgetCategoryLineItemSnapshot> LineItems)
{
    internal decimal LineItemTotal => LineItems.Where(item => !item.IsCashflowOnly).Sum(item => item.Amount);
    internal decimal AvailableAmount => AllocatedAmount - LineItemTotal;
}

public sealed record BudgetCategoryGroupSnapshot(
    Guid BudgetYearId,
    string Name,
    bool IsRestricted,
    bool IsTicketingGroup,
    BudgetCategoryYearSnapshot? BudgetYear);

public sealed record BudgetCategoryYearSnapshot(
    Guid Id,
    string Name,
    bool IsArchived);

public sealed record BudgetCategoryLineItemSnapshot(
    Guid Id,
    string Description,
    decimal Amount,
    Guid? ResponsibleTeamId,
    string? ResponsibleTeamName,
    string? Notes,
    LocalDate? ExpectedDate,
    int VatRate,
    bool IsAutoGenerated,
    bool IsCashflowOnly,
    int SortOrder);

public sealed class BudgetSummaryResult
{
    public decimal TotalIncome { get; init; }
    public decimal TotalExpenses { get; init; }
    public decimal NetBalance { get; init; }
    /// <summary>Signed; cashflow-only items excluded.</summary>
    public decimal TotalLineItems { get; init; }
    public required IReadOnlyList<BudgetSliceResult> IncomeSlices { get; init; }
    public required IReadOnlyList<BudgetSliceResult> ExpenseSlices { get; init; }
}

public sealed class BudgetSliceResult
{
    /// <summary>Null for synthesized VAT, reserves, taxes and group available amounts.</summary>
    public Guid? BudgetCategoryId { get; init; }
    public required string Name { get; init; }
    public decimal Amount { get; init; }
    public decimal Percentage { get; init; }
}

    private static readonly IReadOnlyDictionary<string, (string Spanish, string English)[]> ByPrefix = Entries
        .GroupBy(e => e.Prefix, StringComparer.Ordinal)
        .ToDictionary(
            g => g.Key,
            g => g.Select(e => (Normalize(e.Spanish), e.English)).ToArray(),
            StringComparer.Ordinal);

    /// <summary>
    /// The English name when <paramref name="holdedName"/> is the standard Spanish name of a prefix of
    /// <paramref name="number"/>, trying the longest prefix first. A trailing qualifier Holded adds after the
    /// standard name is kept when it has no letters ("Hacienda Pública, IVA soportado 21%"); a word after it makes the
    /// name the association's own. Null for a name the association chose, and
    /// always for member accounts (40/41) and the 629 category accounts, whose names are theirs.
    /// </summary>
    public static string? EnglishName(int number, string? holdedName)
    {
        if (string.IsNullOrWhiteSpace(holdedName)) return null;
        var digits = number.ToString(CultureInfo.InvariantCulture);
        if (digits.Length > 3 && (digits.StartsWith("40", StringComparison.Ordinal)
                || digits.StartsWith("41", StringComparison.Ordinal)
                || digits.StartsWith("629", StringComparison.Ordinal)))
            return null;

        var name = Normalize(holdedName);
        for (var len = Math.Min(4, digits.Length); len >= 1; len--)
        {
            if (!ByPrefix.TryGetValue(digits[..len], out var candidates)) continue;
            foreach (var (spanish, english) in candidates)
            {
                if (string.Equals(name, spanish, StringComparison.Ordinal)) return english;
                if (name.StartsWith(spanish + " ", StringComparison.Ordinal)
                    && !name[spanish.Length..].Any(char.IsLetter))
                    return english + name[spanish.Length..];
            }
        }
        return null;
    }

    /// <summary>Case, accents, quote marks and repeated spaces don't make a name non-standard.</summary>
    internal static string Normalize(string s)
    {
        var decomposed = s.Normalize(NormalizationForm.FormD);
        var sb = new StringBuilder(decomposed.Length);
        var lastWasSpace = true;
        foreach (var c in decomposed)
        {
            if (CharUnicodeInfo.GetUnicodeCategory(c) == UnicodeCategory.NonSpacingMark) continue;
            if (c is '«' or '»' or '"' or '\'') continue;
            if (char.IsWhiteSpace(c))
            {
                if (!lastWasSpace) sb.Append(' ');
                lastWasSpace = true;
                continue;
            }
            sb.Append(char.ToLowerInvariant(c));
            lastWasSpace = false;
        }
        return sb.ToString().TrimEnd();
    }
